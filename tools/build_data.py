"""Build prototype/js/data.js from the Horizon Power remote communities spreadsheet.

Usage: python3 tools/build_data.py path/to/RESP_communities.xlsx

Only public fields are written out (name, other names, location, region).
Internal columns such as document management IDs and links are left out.
"""
import json
import re
import sys
from pathlib import Path

import openpyxl

SHEET = "Remote Communities-consolidated"
# Horizon Power's own district codes ("HP RC District" column), grouped into its four service areas.
REGIONS = {
    "WKIM": "kimberley",
    "EKIM": "kimberley",
    "WPIL": "pilbara",
    "EPIL": "pilbara",
    "GS-NOMW/COMW": "gascoyne",
    "CEMW": "goldfields",
}
# Names confirmed in the brief and Figma, where the community's own name
# differs from the name used in the spreadsheet.
NAME_OVERRIDES = {
    "Blackstone": ("Papulankutja", ["Blackstone"]),
}


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def split_name(text):
    """'Baulu Wah (Violet Valley)' -> ('Baulu Wah', ['Violet Valley'])."""
    text = " ".join(text.split())
    names = [n.strip() for n in re.findall(r"\(([^)]+)\)", text)]
    base = re.sub(r"\s*\([^)]*\)", "", text).strip()
    return base, names


def main(xlsx):
    wb = openpyxl.load_workbook(xlsx, data_only=True)
    ws = wb[SHEET]
    comments = {}
    for row in wb["Latlongs"].iter_rows(min_row=2, values_only=True):
        if row[0] and row[6]:
            comments[row[0].strip()] = row[6].strip()

    communities = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        source_name, lat, lng, _, contract_name = row[:5]
        district = row[10]
        if not source_name:
            continue
        source_name = source_name.strip()
        if source_name in NAME_OVERRIDES:
            name, other = NAME_OVERRIDES[source_name]
            other = list(other)
        else:
            name, other = split_name(source_name)
        contract_base, contract_other = split_name(contract_name or "")
        for alt in [contract_base, *contract_other, comments.get(source_name)]:
            if alt and alt.lower() != name.lower() and alt.lower() not in (o.lower() for o in other):
                other.append(alt)
        communities.append({
            "id": slugify(name),
            "name": name,
            "otherNames": other,
            "lat": round(float(lat), 4),
            "lng": round(float(lng), 4),
            "region": REGIONS[district.strip()],
        })

    communities.sort(key=lambda c: c["name"].lower())
    ids = [c["id"] for c in communities]
    assert len(ids) == len(set(ids)), "duplicate community ids"

    out = Path(__file__).resolve().parent.parent / "prototype" / "js" / "data.js"
    body = json.dumps(communities, indent=1, ensure_ascii=False)
    out.write_text(
        "// Generated by tools/build_data.py from the RC communities spreadsheet. Do not edit by hand.\n"
        f"window.RC_COMMUNITIES = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(communities)} communities to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
